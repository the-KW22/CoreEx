import { expect, test } from "@playwright/test";
import { expectNoViolations, newApplication, signIn } from "./helpers";

test("writes a Cover Letter linked to a Resume and keeps sender details on unlink", async ({ page }) => {
  test.setTimeout(120_000);
  const stamp = Date.now();
  const resume = `Letter source ${stamp}`;
  const letter = `Letter ${stamp}`;
  await signIn(page);
  await page.goto("/career/library");
  await page.getByRole("button", { name: "New Resume", exact: true }).click();
  const cv = page.getByRole("dialog", { name: "New Resume" });
  await cv.getByLabel("Name").fill(resume);
  await cv.getByLabel("Start with sample content").check();
  await cv.getByRole("button", { name: "Create Resume" }).click();
  await expect(cv).toHaveCount(0);
  const resumeHref = await page.getByRole("link", { name: resume, exact: true }).getAttribute("href");
  await page.goto("/career/cover-letters");
  await page.getByRole("button", { name: "New Cover Letter" }).click();
  const create = page.getByRole("dialog", { name: "New Cover Letter" });
  await create.getByLabel("Name", { exact: true }).fill(letter);
  await create.getByLabel("Linked Resume").selectOption({ label: resume });
  await create.getByRole("button", { name: "Create Cover Letter" }).click();
  await expect(create).toHaveCount(0);
  await page.getByRole("link", { name: letter, exact: true }).click();
  await expect(page.getByLabel("Name", { exact: true })).toHaveValue("Alex Morgan");
  await expect(page.getByLabel("Name", { exact: true })).toBeDisabled();
  const body = page.getByRole("textbox", { name: "Body", exact: true });
  await body.fill("Experience writing reliable software.");
  await body.press("Control+z");
  await expect(body).not.toContainText("Experience writing reliable software.");
  await body.press("Control+Shift+z");
  await expect(body).toContainText("Experience writing reliable software.");
  await expect(page.getByRole("img", { name: /Page 1 of/ })).toBeVisible({ timeout: 30_000 });
  const resumePage = await page.context().newPage();
  await resumePage.goto(resumeHref!);
  await resumePage.getByLabel("Name", { exact: true }).fill("Updated Sender");
  await expect(resumePage.getByRole("status").filter({ hasText: /^Saved$/ })).toBeVisible({ timeout: 20_000 });
  await page.bringToFront();
  await expect(page.getByLabel("Name", { exact: true })).toHaveValue("Updated Sender", { timeout: 20_000 });
  await page.getByLabel("Recipient").fill("Hiring team");
  await expect(page.getByRole("status").filter({ hasText: /^Saved$/ })).toBeVisible({ timeout: 20_000 });
  await page.getByRole("button", { name: "Unlink", exact: true }).click();
  await expect(page.getByLabel("Name", { exact: true })).toBeEnabled();
  await expect(page.getByLabel("Name", { exact: true })).toHaveValue("Updated Sender");
  await expectNoViolations(page);
  await page.reload();
  await expect(page.getByLabel("Recipient")).toHaveValue("Hiring team");
  await expect(page.getByLabel("Name", { exact: true })).toHaveValue("Updated Sender");
});

test("drafts a letter and keeps the sent documents on the Application", async ({ page }) => {
  test.skip(process.env.E2E_FAKE_AI !== "1", "Requires the local fake AI provider");
  test.setTimeout(120_000);
  const stamp = Date.now();
  const company = `Letter company ${stamp}`;
  const resume = `Draft source ${stamp}`;
  const letter = `Draft letter ${stamp}`;
  await signIn(page);
  await newApplication(page, company, "Engineer");
  const applicationPath = new URL(page.url()).pathname;
  await page.goto("/career/library");
  await page.getByRole("button", { name: "New Resume", exact: true }).click();
  const cv = page.getByRole("dialog", { name: "New Resume" });
  await cv.getByLabel("Name").fill(resume);
  await cv.getByLabel("Start with sample content").check();
  await cv.getByRole("button", { name: "Create Resume" }).click();
  await expect(cv).toHaveCount(0);
  await page.goto("/career/cover-letters");
  await page.getByRole("button", { name: "New Cover Letter" }).click();
  const create = page.getByRole("dialog", { name: "New Cover Letter" });
  await create.getByLabel("Name", { exact: true }).fill(letter);
  await create.getByLabel("Linked Resume").selectOption({ label: resume });
  await create.getByRole("button", { name: "Create Cover Letter" }).click();
  await expect(create).toHaveCount(0);
  await page.getByRole("link", { name: letter, exact: true }).click();
  const drafts = page.getByRole("region", { name: "Draft with AI" });
  await drafts.getByLabel("Application").selectOption({ label: `Engineer at ${company}` });
  await drafts.getByLabel("Resume").selectOption({ label: resume });
  await drafts.getByRole("button", { name: "Draft", exact: true }).click();
  await expect(drafts.getByRole("heading", { name: "Suggestion" })).toBeVisible({ timeout: 30_000 });
  await drafts.getByRole("button", { name: "Shorter", exact: true }).click();
  await expect(drafts.getByText("Previous drafts")).toBeVisible();
  await drafts.getByRole("button", { name: "More personal", exact: true }).click();
  await drafts.getByRole("button", { name: "Accept", exact: true }).click();
  await expect(drafts.getByRole("heading", { name: "Suggestion" })).toHaveCount(0);
  await expect(page.getByRole("textbox", { name: "Body", exact: true })).not.toBeEmpty();
  await page.goto(applicationPath);
  const documents = page.locator("section").filter({ has: page.getByRole("heading", { name: "Resumes and Cover Letters" }) });
  await documents.getByRole("combobox", { name: "Resume", exact: true }).selectOption({ label: resume });
  await documents.getByRole("button", { name: "Save Resume link" }).click();
  await documents.getByRole("combobox", { name: "Cover Letter", exact: true }).selectOption({ label: letter });
  await documents.getByRole("button", { name: "Save Cover Letter link" }).click();
  await page.getByRole("button", { name: "Applied", exact: true }).click();
  await expect(page.getByRole("button", { name: "Applied", exact: true })).toHaveAttribute("aria-current", "step");
  await expect(documents.getByText(`Sent: ${resume}`, { exact: false })).toBeVisible();
  await expect(documents.getByText(`Sent: ${letter}`, { exact: false })).toBeVisible();
  await expect(documents.getByRole("combobox", { name: "Resume", exact: true })).toBeDisabled();
  await expectNoViolations(page);
});
