import { expect, test } from "@playwright/test";
import { expectNoViolations, signIn } from "./helpers";

test("checks a Resume, reads its PDF and compares it with an Application", async ({ page }) => {
  test.setTimeout(120_000);
  const name = `Check ${Date.now()}`;
  await signIn(page);
  await page.goto("/career/applications");
  await page.getByRole("button", { name: "New Application" }).click();
  const application = page.getByRole("dialog", { name: "New Application" });
  await application.getByLabel("Company").fill(name);
  await application.getByLabel("Role").fill("Developer");
  await application.getByLabel("Posting", { exact: true }).fill("JavaScript Kubernetes");
  await application.getByRole("button", { name: "Add Application" }).click();
  await expect(page).toHaveURL(/\/career\/applications\//);
  await page.goto("/career/library");
  await page.getByRole("button", { name: "New Resume" }).click();
  const dialog = page.getByRole("dialog", { name: "New Resume" });
  await dialog.getByLabel("Name").fill(name);
  await dialog.getByRole("button", { name: "Create Resume" }).click();
  await page.getByRole("link", { name }).click();
  await page.getByLabel("Name", { exact: true }).fill(name);
  await page.getByRole("button", { name: "Check", exact: true }).click();
  const email = page.getByRole("listitem").filter({ hasText: "Add an email address" });
  await email.getByRole("button", { name: "Ignore" }).click();
  await expect(email).toContainText("Ignored");
  await expect(page.getByRole("status").filter({ hasText: /^Saved$/ })).toBeVisible({ timeout: 15_000 });
  await page.reload();
  await page.getByRole("button", { name: "Check", exact: true }).click();
  await expect(page.getByRole("listitem").filter({ hasText: "Add an email address" })).toContainText("Ignored");
  await page.getByRole("button", { name: "Write", exact: true }).click();
  await page.getByLabel("Email", { exact: true }).fill("invalid-email");
  await page.getByRole("button", { name: "Check", exact: true }).click();
  await page.getByRole("button", { name: /Issue \d+: Check the email address/ }).click();
  await expect(page.getByLabel("Email", { exact: true })).toBeFocused();
  await page.getByRole("button", { name: "Check", exact: true }).click();
  await page.getByRole("button", { name: "See what a parser reads" }).click();
  await expect(page.getByRole("region", { name: "Text read from PDF" })).toContainText(name);
  await page.getByRole("button", { name: "Check exported PDF" }).click();
  await expect(page.getByText("PDF text matches the Resume.")).toBeVisible();
  await page.getByLabel("Application", { exact: true }).selectOption({ label: `Developer at ${name} · ${name}` });
  const missing = page.getByRole("listitem").filter({ hasText: "kubernetes" });
  await expect(missing).toContainText("Missing");
  await missing.getByRole("button", { name: "Not true for me" }).click();
  await expect(missing).toContainText("Not true for me");
  await expect(page.getByRole("status").filter({ hasText: /^Saved$/ })).toBeVisible({ timeout: 15_000 });
  await page.reload();
  await page.getByRole("button", { name: "Check", exact: true }).click();
  await page.getByLabel("Application", { exact: true }).selectOption({ label: `Developer at ${name} · ${name}` });
  await expect(page.getByRole("listitem").filter({ hasText: "kubernetes" })).toContainText("Not true for me");
  await expectNoViolations(page);
});
